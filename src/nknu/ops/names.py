def link_name(word: str) -> str:
    return LINKS.get(word) or NAMES.get(word) or rename(word)


def link_tip(tip: str) -> str:
    """A 對帳 row's hover: each 「name：n」 line renamed; an explaining sentence shortened or left out."""
    out = []
    for line in (tip or "").split("\n"):
        m = _LINE.match(line.strip())
        if m:
            out.append(f"{link_name(m.group(1))}：{m.group(2)}")
        elif line.strip():
            new = NOTES.get(line.strip(), line.strip())
            if new:
                out.append(new)
    return "\n".join(out)
