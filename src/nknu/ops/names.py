_TAIL = re.compile(r"^.*\((內容在按鈕行|學校把公告轉到別的頁)\)$")


def rename(word: str) -> str:
    if word in NAMES:
        return NAMES[word]
    for head, new in (("待確認：", "待確認："), ("沒有檔案：", "無檔案："), ("成為文件：", "文件：")):
        if word.startswith(head):
            rest = word[len(head):]
            return new + NAMES.get(rest, rest)
    m = _TAIL.match(word)
    if m:
        return NAMES.get(m.group(1).replace("學校把公告轉到別的頁", "學校把這則公告轉到別的頁"), m.group(1))
    return word


def merge(pairs):
    """[[word, n], …] renamed, the same new word's counts summed, in order of size."""
    out = {}
    for w, n in pairs:
        k = rename(w)
        out[k] = out.get(k, 0) + n
    return [[k, n] for k, n in sorted(out.items(), key=lambda kv: -kv[1])]


